/* =====================================================================
 * 概念3: CSVライタを自作する(カンマ・改行・ダブルクォートのエスケープ)
 * ---------------------------------------------------------------------
 * ■ なぜ:
 *   C#では CsvHelper の CsvWriter.WriteRecords(...) がフィールドの
 *   エスケープを全部やってくれます。しかし内部で何をしているかを知らないと、
 *   「値にカンマが入っていたら列がズレた」「ダブルクォート入りの文字列で
 *   壊れたCSVができた」といった事故に対処できません。CSVの仕様(RFC4180)は
 *   実はシンプルなルールで成り立っています。
 *
 * ■ 解説:
 *   CSV(Comma-Separated Values)は、フィールドをカンマで区切っただけの
 *   単純なテキストです。しかしフィールドの値自体にカンマや改行が
 *   含まれていたらどうなるか? そこで生まれたルールが:
 *
 *     1. フィールドにカンマ・改行・ダブルクォートのどれかが含まれる場合、
 *        フィールド全体をダブルクォート " で囲む
 *     2. フィールド内にダブルクォートがあれば "" (2個)に置き換える
 *        (ダブルクォートで囲んだ中で " が1個だけ出てくると
 *        「ここでフィールドが終わった」と誤解されてしまうため)
 *
 *   例: 値が a,b なら "a,b" という1フィールドとして出力する。
 *       値が 5"cm なら "5""cm" という1フィールドとして出力する。
 *
 *   このエスケープを怠ると、Excel等で開いたときに列がズレたり、
 *   文字化けのように見える壊れたファイルになったりします。
 * ===================================================================== */

function check(name: string, actual: unknown, expected: unknown, hint = ""): boolean {
  const ok = actual !== null && actual !== undefined
    && JSON.stringify(actual) === JSON.stringify(expected);
  if (ok) console.log(`[OK] ${name}: 正解!`);
  else {
    console.log(`[NG] ${name}: 期待値 ${JSON.stringify(expected)} / 実際 ${JSON.stringify(actual)}`);
    if (hint) console.log(`     ヒント: ${hint}`);
  }
  return ok;
}

// --- 見る(worked example) ---------------------------------------------
// GOAL: なぜエスケープが必要かを、エスケープしない場合の「壊れたCSV」で確認する

console.log("--- STEP 1: エスケープなしでカンマ入り値をそのまま出力すると… ---");
const nameWithComma = "海辺の詩集、改訂版"; // 実はこれは日本語の読点「、」なのでカンマ(,)ではない
const nameWithRealComma = "本, サブタイトル付き"; // こちらは本物のカンマ
console.log(`price,name\n1000,${nameWithRealComma}`, "\n(→ 列が3つに見えてしまい、CSVとして壊れる)");

console.log("--- STEP 2: ダブルクォートで囲んで対処する ---");
console.log(`price,name\n1000,"${nameWithRealComma}"`, "\n(→ カンマを含む値全体が1フィールドだと分かる)");

console.log("--- STEP 3: 値自体にダブルクォートが含まれる場合 ---");
const nameWithQuote = '5"インチのノート';
const escaped = nameWithQuote.replace(/"/g, '""');
console.log("元の値        :", nameWithQuote);
console.log('""エスケープ後:', escaped);
console.log("最終フィールド:", `"${escaped}"`);

// --- 予測してみよう -----------------------------------------------------
// 次のブロックは、正規表現でエスケープが必要かどうかを判定します。
// 実行前に予測: 3つの値それぞれについて、クォートが必要かどうか(true/false)?
console.log("--- 予測してみよう ---");
const needsQuotePattern = /[",\n\r]/;
const samples = ["文芸書", "本, サブタイトル付き", "改行\nあり"];
for (const s of samples) {
  console.log(JSON.stringify(s), "→ クォート必要?:", needsQuotePattern.test(s));
}

