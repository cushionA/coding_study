// 数値フィールドも文字列化してから同じ関数を通せば安全、という確認。
console.log("--- 変えてみる ---");
console.log("数値1200を文字列化:", String(1200), "→ カンマや改行を含まないのでクォート不要");

// --- 書いてみる ---------------------------------------------------------
// 課題: 値 5"cm(ダブルクォートを含む)を正しくCSVエスケープした文字列を
//       result3 に入れてください(期待値: '"5""cm"'。ダブルクォートで囲まれ、
//       中の " が "" になっている)。
// ヒント(概念レベル): まず .replace(/"/g, '""') で内部の " を2重化し、
//       その結果全体をダブルクォートで囲む
let result3: string | null = null;
// ここに書く(result3 に代入する)

check("概念3: ダブルクォートのエスケープ", result3, '"5""cm"',
  '元の値 5"cm に対して .replace(/"/g, \'""\') してから、結果全体を " で囲む');

